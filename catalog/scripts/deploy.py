#!/usr/bin/env python3
"""Deploy a project map: write every routed agent, composed inside its aspect, into a real project's .claude/.

Usage:
    deploy.py ../projects/smart-thermostat/project-map.yaml --target ~/src/smart-thermostat
    deploy.py                                   # .kitbash/project-map.yaml here or in a parent, into its project
    deploy.py MAP --target DIR --dry-run        # print the files, write nothing
    deploy.py MAP --target DIR --force          # overwrite files in .claude/agents/ that Kitbash did not write

Each (aspect, agent) pair becomes one Claude Code subagent file, .claude/agents/<agent>.md
(<agent>-<aspect>.md when an agent is routed in more than one aspect), composed exactly as run_evals.py
composes it for an eval: the map's pack base, traits, skills, the skills of the aspect's tools, the prompt.
So what was evaluated is what is deployed. The frontmatter carries the rest of the taxonomy:
    model             the aspect's preferred_llm, else the agent's
    disallowedTools   tools denied by traits (minus overrides.allow), plus every MCP tool in the catalog
                      that is not bound to this aspect, so tools of other aspects are never mounted
    mcpServers        inline definitions of the aspect's MCP tools, connected only while this agent runs
    hooks             the agent's hooks, copied to .claude/kitbash/hooks/
The description names the aspect and its paths, which is how Claude Code routes work to the agent.

A manifest at .claude/kitbash.json records what was written. A later deploy overwrites those files, removes
the ones no longer produced, and refuses to touch a file it did not write unless --force is given.
The map, its catalog and its playbooks must validate first; nothing is written otherwise.

plan_plugins is the plugin form of the same composition, used by release.py. It groups aspects by the git checkout
holding their paths, one plugin per repo. Plugin subagents ignore `hooks` and `mcpServers`, so an agent's hooks move to
the plugin's hooks/hooks.json behind only-for-agents.py, which runs them only inside that agent, and a map that binds
an MCP tool is refused.
"""
import argparse
import json
import os
import re
import shutil
import stat
import sys
import time

import run_evals as R
import validate as V  # before yaml: validate falls back to the vendored PyYAML
import yaml

MANIFEST = ".claude/kitbash.json"
HOOK_DIR = ".claude/kitbash/hooks"


def routed(pm):
    """[(aspect, agent)] in map order."""
    return [(asp, ag) for asp, cfg in (pm.get("aspects") or {}).items() for ag in V.as_list((cfg or {}).get("agents"))]


def agent_file(asp, ag, pm, cat, map_path, unique, plugin_paths=None):
    """(relative path, text, hook sources) for one agent composed inside one aspect.

    plugin_paths, the aspect's paths relative to its repo, selects the plugin form of the file."""
    plugin = plugin_paths is not None
    agent, _ = cat["agents"][ag]
    tool_names, pack = R.aspect_context(map_path, asp, cat)
    prompt, denied, hooks = R.compose(agent, cat, tool_names, pack)
    cfg = pm["aspects"][asp] or {}
    mcp_here = [t for t in tool_names if cat["tools"][t][0].get("kind") == "mcp"]
    if plugin and mcp_here:
        sys.exit(f"a plugin cannot bind MCP tools yet: aspect '{asp}' binds {mcp_here}")
    mcp_elsewhere = sorted(t for t, (d, _) in cat["tools"].items() if d.get("kind") == "mcp" and t not in tool_names)
    paths = plugin_paths if plugin else V.as_list(cfg.get("paths"))

    fm = {
        "name": ag if unique else f"{ag}-{asp}",
        "description": (f"{agent.get('description', '').strip()} Works in the '{asp}' aspect of {pm['project']}"
                        + (f", paths: {', '.join(paths)}." if paths else ".")),
        "model": cfg.get("preferred_llm") or agent["preferred_llm"],
    }
    disallowed = list(denied) + [f"mcp__{t}" for t in mcp_elsewhere]
    if disallowed:
        fm["disallowedTools"] = disallowed
    if mcp_here:
        fm["mcpServers"] = [{t: V.server_config(cat["tools"][t][0])} for t in mcp_here]
    if hooks and not plugin:
        fm["hooks"] = {"PreToolUse": [{"matcher": "", "hooks": [
            {"type": "command", "command": f'"$CLAUDE_PROJECT_DIR"/{HOOK_DIR}/{os.path.basename(h)}'} for h in hooks]}]}
    text = ("---\n" + yaml.safe_dump(fm, sort_keys=False, width=1000, allow_unicode=True) + "---\n"
            f"<!-- generated by Kitbash deploy.py from {os.path.basename(map_path)}; edit the catalog, not this file -->\n\n"
            + prompt + "\n")
    return f"{'agents' if plugin else '.claude/agents'}/{fm['name']}.md", text, hooks


def warn_license(rel, ag, cat):
    for s in V.as_list(cat["agents"][ag][0].get("skills")):
        d = cat["skills"][s][0]
        if "_source" in d and re.search(r"proprietary|all rights reserved", d.get("_license") or "", re.I):
            print(f"warning  {rel} composes imported skill '{s}' whose license reads: {d['_license']}")


def plan(map_path, pm, cat):
    """{relative path: text or source path to copy}."""
    pairs = routed(pm)
    count = {}
    for _, ag in pairs:
        count[ag] = count.get(ag, 0) + 1
    files = {}
    for asp, ag in pairs:
        rel, text, hooks = agent_file(asp, ag, pm, cat, map_path, count[ag] == 1)
        files[rel] = text
        warn_license(rel, ag, cat)
        for h in hooks:
            files[f"{HOOK_DIR}/{os.path.basename(h)}"] = ("copy", h)
    return files


def git_root(path):
    """The git checkout holding path, or None."""
    d = path
    while d != os.path.dirname(d):
        if os.path.exists(os.path.join(d, ".git")):
            return d
        d = os.path.dirname(d)
    return None


def repo_of(asp, pm, target):
    """The git checkout holding an aspect's paths, which are relative to target or absolute."""
    paths = V.as_list((pm["aspects"][asp] or {}).get("paths"))
    repos = {git_root(os.path.join(target, p.split("*")[0].rstrip("/"))) for p in paths}
    if len(repos) != 1 or None in repos:
        sys.exit(f"a plugin needs each aspect in one git repo: aspect '{asp}' has paths {paths} under {target}")
    return repos.pop()


def plan_plugins(map_path, pm, cat, target):
    """(files, agents), one plugin per repo.

    files is {path relative to target, or absolute outside it: text or source path to copy}.
    agents is {(aspect, agent): {plugin, file, text, hooks}}."""
    by_repo = {}
    for asp, ag in routed(pm):
        by_repo.setdefault(repo_of(asp, pm, target), []).append((asp, ag))
    files, agents = {}, {}
    for repo, pairs in by_repo.items():
        name = os.path.basename(repo).lower()
        root = os.path.join(repo, ".claude", "skills", name)
        if root.startswith(target + os.sep):
            root = root[len(target) + 1:]
        names = [ag for _, ag in pairs]
        guarded = {}  # hook script: the plugin-scoped agents it applies to
        for asp, ag in pairs:
            in_repo = [os.path.join(target, p)[len(repo) + 1:] for p in V.as_list((pm["aspects"][asp] or {}).get("paths"))]
            rel, text, hooks = agent_file(asp, ag, pm, cat, map_path, names.count(ag) == 1, plugin_paths=in_repo)
            files[f"{root}/{rel}"] = text
            agents[(asp, ag)] = {"plugin": name, "file": rel, "text": text, "hooks": hooks}
            warn_license(f"{root}/{rel}", ag, cat)
            for h in hooks:
                guarded.setdefault(h, []).append(f"{name}:{os.path.splitext(os.path.basename(rel))[0]}")
        files[f"{root}/.claude-plugin/plugin.json"] = json.dumps(
            {"name": name, "description": f"Kitbash agents for the {name} repo of {pm['project']}."}, indent=2) + "\n"
        if guarded:
            guard = os.path.join(cat["dir"], "hooks", "only-for-agents.py")
            files[f"{root}/hooks/{os.path.basename(guard)}"] = ("copy", guard)
            commands = []
            for h, scoped in guarded.items():
                files[f"{root}/hooks/{os.path.basename(h)}"] = ("copy", h)
                commands.append({"type": "command", "command": '"${CLAUDE_PLUGIN_ROOT}/hooks/only-for-agents.py" '
                                 f'"${{CLAUDE_PLUGIN_ROOT}}/hooks/{os.path.basename(h)}" ' + " ".join(scoped)})
            files[f"{root}/hooks/hooks.json"] = json.dumps(
                {"hooks": {"PreToolUse": [{"matcher": "", "hooks": commands}]}}, indent=2) + "\n"
    return files, agents


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("map", nargs="?", help=f"default {V.PROJECT_DIR}/project-map.yaml here or in a parent directory")
    ap.add_argument("--target", help=f"root of the real project to deploy into; default the project of a map in a "
                                     f"{V.PROJECT_DIR} folder")
    ap.add_argument("--dry-run", action="store_true")
    ap.add_argument("--force", action="store_true")
    opts = ap.parse_args()

    opts.map = opts.map or V.find_project_map()
    if not opts.map:
        ap.error(f"give a map, or run inside a project with a {V.PROJECT_DIR}/project-map.yaml")
    map_path = os.path.abspath(opts.map)
    opts.target = opts.target or V.project_root(map_path)
    if not opts.target:
        ap.error(f"--target is required for a map outside a {V.PROJECT_DIR} folder")
    target = os.path.abspath(os.path.expanduser(opts.target))
    if not os.path.isdir(target):
        sys.exit(f"target is not a directory: {target}")
    rep = V.Report()
    V.check_project_map(map_path, rep, {})
    if rep.errors:
        print("\n".join(f"error    {e}" for e in rep.errors))
        sys.exit("catalog, map or playbook does not validate; fix it before deploying")
    pm = yaml.safe_load(open(map_path))
    cat_dir = V.catalog_dir(map_path, pm.get("catalog"))
    cat = V.load_catalog(cat_dir, V.Report())

    files = plan(map_path, pm, cat)
    if opts.dry_run:
        for rel, content in files.items():
            print(f"\n----- {rel}" + (f"  (copy of {content[1]})" if isinstance(content, tuple) else f"\n{content}"))
        print(f"\n(dry run, nothing written; {len(files)} file(s) for {target})")
        return 0

    mpath = os.path.join(target, MANIFEST)
    previous = set(json.load(open(mpath)).get("files", [])) if os.path.exists(mpath) else set()
    foreign = [rel for rel in files if os.path.exists(os.path.join(target, rel)) and rel not in previous]
    if foreign and not opts.force:
        sys.exit("refusing to overwrite files Kitbash did not write (use --force):\n  " + "\n  ".join(foreign))

    for rel, content in files.items():
        path = os.path.join(target, rel)
        os.makedirs(os.path.dirname(path), exist_ok=True)
        if isinstance(content, tuple):
            shutil.copyfile(content[1], path)
            os.chmod(path, os.stat(path).st_mode | stat.S_IXUSR | stat.S_IXGRP | stat.S_IXOTH)
        else:
            open(path, "w").write(content)
        print(f"wrote    {rel}")
    for rel in sorted(previous - set(files)):
        path = os.path.join(target, rel)
        if os.path.exists(path):
            os.remove(path)
            print(f"removed  {rel}  (no longer in the map)")
    os.makedirs(os.path.dirname(mpath), exist_ok=True)
    json.dump({"project": pm["project"], "map": map_path, "catalog": cat_dir,
               "deployed": time.strftime("%Y-%m-%dT%H:%M:%S%z"), "files": sorted(files)},
              open(mpath, "w"), indent=2)
    print(f"\n{len(files)} file(s) deployed to {target}; manifest at {MANIFEST}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
